"""Reproducible local plugin packages generated from canonical definitions.

Static format/integrity validation only; no installation, publication or host calls.
"""

from __future__ import annotations

from pathlib import Path

from . import __version__
from .adapters import render
from .catalog import asset, skills
from .fs import AgentBaseError, batch_write, confined, digest, json_text, project_lock, read_json, relative
from .skill_security import metadata


def files(provider: str) -> dict[str, str]:
    if provider not in {"codex", "claude"}:
        raise AgentBaseError("Unsupported plugin provider.")
    manifest = {"name": "agentbase", "version": __version__, "description": "AgentBase on-demand development workflows",
                "author": {"name": "AgentBase contributors"}}
    generated = {f"skills/{name}/SKILL.md": body for name, body in skills().items()}
    generated["LICENSE"] = asset("license.md")
    if provider == "claude":
        generated[".claude-plugin/plugin.json"] = json_text(manifest)
        generated[".claude-plugin/marketplace.json"] = json_text({"name": "agentbase-local", "metadata": {"description": "Local AgentBase development workflows"}, "owner": {"name": "AgentBase contributors"},
            "plugins": [{"name": "agentbase", "source": "./", "description": manifest["description"]}]})
        for name, content in render(["claude"]).items():
            if name.startswith(".claude/agents/"):
                generated["agents/" + name.rsplit("/", 1)[1]] = content
    else:
        generated["plugin.json"] = json_text(manifest | {"$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json"})
        generated[".codex-plugin/plugin.json"] = json_text(manifest | {"skills": "./skills/"})
        # Standalone Codex agents remain generated by init. Plugin discovery of
        # custom-agent TOML is not asserted without a documented contract.
    generated["README.md"] = ("# AgentBase local plugin\n\n"
        "Requires Python 3.11+ and agentbase-toolkit for CLI workflows. Install the\n"
        "Python CLI separately and run `agentbase init --discovery plugin` in your project before using\n"
        "tasks/memory/context workflows. Avoid installing duplicate standalone and\n"
        "plugin skills in the same host; choose one discovery route. This package\n"
        "runs no hooks and installs no dependencies. Upgrade by regenerating into a\n"
        "new directory and reviewing the diff. No marketplace publication or runtime\n"
        "approval is implied by static validation.\n")
    generated["package.lock.json"] = json_text({"schema_version": 1, "provider": provider,
        "files": {name: digest(content) for name, content in generated.items()}})
    return generated


def build(root: Path, provider: str, output: str, *, dry_run: bool = False) -> dict:
    output = relative(output)
    generated = files(provider)

    def prepare():
        changes = {}
        for name, content in generated.items():
            dest = f"{output}/{name}"
            path = confined(root, dest)
            if path.exists():
                if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
                    raise AgentBaseError("Existing plugin output differs; choose a new output directory: " + dest)
            else:
                changes[dest] = content
        return changes
    if dry_run:
        changes = prepare()
    else:
        with project_lock(root):
            changes = prepare()
            batch_write(root, changes)
    return {"provider": provider, "output": output, "dry_run": dry_run, "files": sorted(generated),
            "written": len(changes), "published": False, "runtime_verified": False}


def validate(root: Path, output: str) -> dict:
    output = relative(output)
    lock = read_json(confined(root, f"{output}/package.lock.json"))
    if lock.get("schema_version") != 1 or lock.get("provider") not in {"codex", "claude"} or not isinstance(lock.get("files"), dict):
        raise AgentBaseError("Invalid distribution integrity manifest.")
    # Validate against this CLI's actual canonical files, not only a mutable lock.
    expected = files(lock["provider"])
    for name, content in expected.items():
        path = confined(root, f"{output}/{name}")
        if not path.is_file() or path.read_bytes() != content.encode("utf-8"):
            raise AgentBaseError("Plugin differs from canonical package: " + name)
        if name.endswith("/SKILL.md"):
            metadata(content, name.split("/")[-2])
    base = confined(root, output)
    for path in base.rglob("*"):
        confined(root, path.relative_to(root).as_posix())
        if path.is_file() and path.relative_to(base).as_posix() not in expected:
            raise AgentBaseError("Unexpected file in plugin package: " + path.name)
    return {"ok": True, "provider": lock["provider"], "validation": "canonical files, metadata and hashes",
            "runtime_verified": False, "provider_validator_executed": False}
